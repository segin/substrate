#ifndef _SYS_SIGNAL_H
#define _SYS_SIGNAL_H 1

/*
 * Historical location of the signal definitions.  POSIX places them in
 * <signal.h>; BSD and glibc keep this <sys/signal.h> compatibility header
 * that simply forwards there.  Old sources (CDE's libcsa, ToolTalk, ...)
 * include it.
 */
#include <signal.h>

#endif /* _SYS_SIGNAL_H */
