/* POSIX sa_flags values — MUST match include/signal.h (the userland
 * ABI) bit-for-bit.  Userland and kernel share the same `int sa_flags`
 * across the sigaction() syscall boundary; any drift between the two
 * headers turns SA_ONSTACK/SA_RESTART/SA_NODEFER/SA_RESETHAND into
 * silent no-ops.  Caught by tests/lib/c/torture_sigalrm sc4. */
#define SA_NOCLDSTOP 0x00000001
#define SA_NOCLDWAIT 0x00000002
#define SA_SIGINFO   0x00000004
#define SA_ONSTACK   0x00000008
#define SA_RESTART   0x00000010
#define SA_NODEFER   0x00000020
#define SA_RESETHAND 0x00000040

#ifndef __sigval_t_defined
#define __sigval_t_defined 1
union sigval {
    int   sival_int;
    void *sival_ptr;
};
#endif

typedef struct {
    int      si_signo;    /* Signal number */
    int      si_errno;    /* An errno value */
    int      si_code;     /* Signal code */
    int      si_pid;      /* Sending process ID */
    unsigned int si_uid;  /* Real user ID of sending process */
    void    *si_addr;     /* Memory location which caused fault */
    int      si_status;   /* Exit value or signal */
    union sigval si_value; /* sigqueue(2) payload (SI_QUEUE) */
    // Padding to 128 bytes usually
    int      _pad[25];
} siginfo_t;

/*
 * POSIX real-time signal queue (per process — see rtsig_q[] in proc.h).
 *
 * RTSIG_QUEUE_MAX bounds the number of simultaneously-queued RT-signal
 * instances a process may hold; sigqueue(2) returns EAGAIN once it is
 * reached (>= _POSIX_SIGQUEUE_MAX = 32).  Each occupied slot is one
 * pending instance carrying its own si_value/si_code.  rt_signo == 0
 * marks a free slot; rt_seq is a per-process monotonic FIFO key so the
 * oldest instance of a given signo is delivered first.
 */
#define RTSIG_QUEUE_MAX 64

struct rtsig_entry {
    uint16_t     rt_signo;   /* 0 = free slot, else the signal number  */
    int16_t      rt_code;    /* si_code (SI_USER / SI_QUEUE)            */
    uint32_t     rt_seq;     /* FIFO ordering key (per-process)        */
    union sigval rt_value;   /* si_value payload delivered to handler  */
    int32_t      rt_pid;     /* sending process pid   (siginfo si_pid) */
    uint32_t     rt_uid;     /* sending process ruid  (siginfo si_uid) */
};

