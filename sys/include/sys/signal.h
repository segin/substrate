/*
 * POSIX asynchronous-event notification (struct sigevent) — the kernel only
 * consumes this for mq_notify(2), so it needs the SIGEV_SIGNAL fields.  Layout
 * MUST match the userland <signal.h> copy: it crosses the syscall boundary.
 */
#ifndef __sigval_t_defined
#define __sigval_t_defined 1
union sigval {
    int   sival_int;
    void *sival_ptr;
};
#endif

#define SIGEV_SIGNAL  0    /* notify via signal */
#define SIGEV_NONE    1    /* no notification */
#define SIGEV_THREAD  2    /* notify by spawning a thread (userspace only) */

struct sigevent {
    int            sigev_notify;               /* SIGEV_* */
    int            sigev_signo;                /* signal number (SIGEV_SIGNAL) */
    union sigval   sigev_value;                /* value passed to handler/thread */
    void         (*sigev_notify_function)(union sigval); /* SIGEV_THREAD */
    void          *sigev_notify_attributes;    /* pthread_attr_t * (SIGEV_THREAD) */
};

void psignal(struct process *p, int sig);
/* Post SIGCHLD to `parent` carrying a child status-change siginfo: si_code is
 * one of CLD_* and si_pid/si_uid/si_status describe the child, so a parent's
 * SA_SIGINFO SIGCHLD handler sees the correct code (POSIX). */
void sigchld_notify(struct process *parent, int code, int cpid,
                    unsigned int cuid, int status);

/* POSIX interruption policy for a self-restarting interruptible sleep
 * (nanosleep/clock_nanosleep): call after an early wake with signals pending.
 * Returns nonzero iff the sleep must abort with EINTR (a caught or terminating
 * signal is pending); returns 0 when the caller should resume sleeping (any
 * pending job-control stop is honoured in place, ignored signals discarded). */
int signal_sleep_interrupted(void);
void signal_wake_thread(struct thread *t, int sig);
/* Queue one process-wide real-time-signal instance; no-op for standard signals.
 * Returns 0 or -EAGAIN if the RT queue is full.  (Retained for ksyms/ABI; the
 * thread-directed thr_kill/pthread_kill path now uses signal_post_thread, which
 * sets the pending bit on the TARGET thread only.) */
int signal_rt_post(struct process *p, int sig);
/* Post `sig` to a single thread (thread-directed: pthread_kill/thr_kill), then
 * wake it if it is interruptibly blocked.  Handles real-time signals correctly:
 * a bare pending bit with no queued instance is dropped by the delivery path,
 * so an RT signal is enqueued (one instance, pending bit on `t` alone) rather
 * than merely OR'd into t->sig_pending. */
void signal_post_thread(struct thread *t, int sig);
void pgsignal(int pgrp, int sig);
void trapsignal(struct process *p, int sig, int code);
void sigexit(struct process *p, int sig);
void sendsig(void *handler, int sig, uint32_t mask, uint32_t flags, void *regs);

